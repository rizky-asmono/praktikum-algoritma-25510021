package C_Pengkondisian;

public class ContohIf {
    public static void main(String[] args) {
        // if dengan nilai langsung
        if (20 > 18) {
            System.out.println("20 lebih besar dari 18");
        }
 
        // if dengan variabel
        int x = 20;
        int y = 25;
        if (x > y) {
            System.out.println("x lebih besar dari y");
        }
    }

    
}
