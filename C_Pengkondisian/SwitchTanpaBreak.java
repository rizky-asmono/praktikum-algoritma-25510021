package C_Pengkondisian;

public class SwitchTanpaBreak {
        public static void main(String[] args) {
        int day = 2;
        switch (day) {
            case 1:
                System.out.println("Senin");
                break;
            case 2:
                System.out.println("Selasa");
            break;
                case 3:
                System.out.println("Rabu");
            break;
                default:
                System.out.println("Hari lainnya");
        }
    }

    
}
