package B_TipeDataOperator;

public class BiodataMahasiswa {
    public static void main(String[] args) {
        // Deklarasi dan inisialisasi variabel
        String nama = "Andi Pratama";
        int umur = 19;
        double ipk = 3.75;
        char golonganDarah = 'O';
        boolean aktif = true;
        long nomorHp = 81234567890L;
        float tinggiBadan = 170.5f;
 
        System.out.println("Nama          : " + nama);
        System.out.println("Umur          : " + umur + " tahun");
        System.out.println("IPK           : " + ipk);
        System.out.println("Golongan Darah: " + golonganDarah);
        System.out.println("Status Aktif  : " + aktif);
        System.out.println("Nomor HP      : 0" + nomorHp);
        System.out.println("Tinggi Badan  : " + tinggiBadan + " cm");
    }

    
}
